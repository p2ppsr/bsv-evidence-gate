import { createCipheriv, createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const source = resolve(root, 'assets-source/bodycam-demo.mp4')
const output = resolve(root, 'public/evidence/bodycam-demo.mp4.enc')
const generated = resolve(root, 'src/demoEvidence.generated.ts')

const plaintext = await readFile(source)
// This repository contains only fictional public demo evidence. Deterministic
// material keeps source builds reproducible; production keys must be random,
// secret, and managed outside the public application bundle.
const sourceHash = createHash('sha256').update(plaintext).digest('hex')
const key = createHash('sha256').update(`bsv-evidence-gate:demo-key:${sourceHash}`).digest()
const iv = createHash('sha256').update(`bsv-evidence-gate:demo-iv:${sourceHash}`).digest().subarray(0, 12)
const cipher = createCipheriv('aes-256-gcm', key, iv)
const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final(), cipher.getAuthTag()])

await mkdir(dirname(output), { recursive: true })
await writeFile(output, ciphertext)

const sha256 = value => createHash('sha256').update(value).digest('hex')
const moduleSource = `// Generated by scripts/encrypt-evidence.mjs. Public demo material only.\nexport const DEMO_EVIDENCE = ${JSON.stringify({
  keyBase64: key.toString('base64'),
  ivBase64: iv.toString('base64'),
  plaintextSha256: sha256(plaintext),
  ciphertextSha256: sha256(ciphertext),
  plaintextBytes: plaintext.byteLength,
  ciphertextBytes: ciphertext.byteLength,
  localCiphertextUrl: '/evidence/bodycam-demo.mp4.enc'
}, null, 2)} as const\n`
await writeFile(generated, moduleSource)

console.log(`Encrypted ${plaintext.byteLength} bytes; ciphertext SHA-256 ${sha256(ciphertext)}`)
